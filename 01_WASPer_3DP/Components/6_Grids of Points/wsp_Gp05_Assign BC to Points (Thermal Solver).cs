#region Component Description
/*
Component: wsp_Gp03_Assign BC to Points (Thermal Solver)
Category: WASPerformance / 6_Grids of points

Purpose
    Assigns thermal solver boundary-condition point sets from reference geometry.

Inputs
    untrimmed_grid : List<Point3d>
        Grid points generated by Gp01/Gp02.

    bc_1_geo : Geometry
        Geometry representing boundary condition 1.
        Closed Mesh/Brep/Box/Extrusion volumes select points inside or on the volume.
        Open Mesh/Brep/Surface/Curve/Point geometries select the closest grid points
        and a local grid band so the boundary is covered on coarse grids.

    bc_2_geo : Geometry
        Same as bc_1_geo, for boundary condition 2.

Outputs
    bc_1_points : List<Point3d>
        Grid points assigned to BC1.

    bc_2_points : List<Point3d>
        Grid points assigned to BC2. Points already assigned to BC1 are removed
        from BC2 and reported as a warning to avoid conflicting Dirichlet nodes.
*/
#endregion


#region Component Description
/*
Component: wsp_Ro08_KUKA Post Processor
Nickname: kuka_post
Category: WASPer_3DP
SubCategory: 5.1_Robot Gcode

Creates a native Robots IPostProcessor for KUKA systems. Connect its output to
the optional Post Processor (Ps) input of Robots Load Robot System before using
Create Program.

The postprocessor delegates target formatting and command handling to the native
Robots 2.2.5 KRL writer, then applies a WASPer/KUKA profile:
  - KSS template header and standard INI folds
  - configurable PTP speed, $ADVANCE, and $APO.CPTP
  - explicit $IPO_MODE = #BASE for a flange-mounted tool
  - KUKA|prc-compatible initial frame activation without forcing LOAD_DATA
  - optional explicit start-axis fold
  - Speed/Zone REAL attributes inlined numerically into KRL

It does not change target order, kinematics, process-command placement, or the
simulation represented by the Robots Program. An optional start-axis fold adds
a real PTP movement outside the simulated target sequence and must therefore be
used deliberately.
*/
#endregion

